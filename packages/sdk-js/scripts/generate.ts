/**
 * Writes src/generated.ts (TypeScript) and ../sdk-python/src/hrvoice/_generated.py
 * from the API's own OpenAPI document (buildOpenApi in apps/api), so both SDKs
 * follow /v1 exactly. Run: pnpm --filter @hrvoice/sdk generate
 *
 * ponytail: a small JSON Schema -> type printer covering what z.toJSONSchema emits
 * for the /v1 schemas; swap for openapi-typescript if the document grows $defs/allOf.
 */

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { buildOpenApi } from '../../../apps/api/src/integrations/openapi.ts';

type Schema = Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any

const doc = buildOpenApi() as Schema;
const schemas = doc['components']['schemas'] as Record<string, Schema>;
const here = import.meta.dirname;
/** `Error` would shadow the global in TS. */
const nameOf = (n: string) => (n === 'Error' ? 'ErrorBody' : n);

// ---- TypeScript ----

const paren = (t: string) => (t.includes(' | ') ? `(${t})` : t);

function ts(s: Schema, pad = ''): string {
  if (s['$ref']) return nameOf(String(s['$ref']).split('/').pop()!);
  if (s['const'] !== undefined) return JSON.stringify(s['const']);
  if (s['enum']) return (s['enum'] as unknown[]).map((v) => JSON.stringify(v)).join(' | ');
  const alts = s['anyOf'] ?? s['oneOf'];
  if (alts) return (alts as Schema[]).map((a) => ts(a, pad)).join(' | ');
  const t = s['type'];
  if (Array.isArray(t)) return t.map((x) => ts({ ...s, type: x }, pad)).join(' | ');
  switch (t) {
    case 'string':
      return s['format'] === 'binary' ? 'ArrayBuffer' : 'string';
    case 'number':
    case 'integer':
      return 'number';
    case 'boolean':
    case 'null':
      return t;
    case 'array':
      return `${paren(ts(s['items'] ?? {}, pad))}[]`;
    case 'object': {
      const props = s['properties'] as Record<string, Schema> | undefined;
      if (!props) {
        const ap = s['additionalProperties'];
        return `Record<string, ${ap && typeof ap === 'object' ? ts(ap, pad) : 'unknown'}>`;
      }
      const req = new Set<string>(s['required'] ?? []);
      const inner = `${pad}  `;
      const lines = Object.entries(props).map(([k, v]) => {
        const doc = v['description'] ? `${inner}/** ${v['description']} */\n` : '';
        return `${doc}${inner}${k}${req.has(k) ? '' : '?'}: ${ts(v, inner)};`;
      });
      return `{\n${lines.join('\n')}\n${pad}}`;
    }
    default:
      return 'unknown';
  }
}

const jsonOf = (content: Schema | undefined) => content?.['application/json']?.['schema'] as Schema | undefined;

const ops: string[] = [];
for (const [path, item] of Object.entries(doc['paths'] as Record<string, Schema>)) {
  if (!path.startsWith('/v1/')) continue; // /public/* is the candidate's browser, not an API client
  for (const [method, op] of Object.entries(item)) {
    const query = ((op['parameters'] ?? []) as Schema[]).filter((p) => p['in'] === 'query');
    const queryT = query.length
      ? `{ ${query.map((p) => `${p['name']}?: ${ts(p['schema'])}`).join('; ')} }`
      : 'never';
    const body = jsonOf(op['requestBody']?.['content']);
    const ok = Object.entries(op['responses'] as Record<string, Schema>)
      .filter(([code]) => code.startsWith('2'))
      .map(([, r]) => jsonOf(r['content']))
      .filter((x): x is Schema => !!x);
    const parts = ok.map((x) => ts(x, '    '));
    // `A | B` and `A` from two statuses collapse to `A | B` when they are all named types.
    const flat = parts.join(' | ').split(' | ');
    const res = !ok.length ? 'unknown' : flat.every((p) => /^\w+$/.test(p)) ? [...new Set(flat)].join(' | ') : [...new Set(parts)].join(' | ');
    ops.push(
      `  /** ${op['summary']} */\n  '${method.toUpperCase()} ${path}': {\n` +
        `    query: ${queryT};\n    body: ${body ? ts(body, '    ') : 'never'};\n    response: ${res};\n  };`,
    );
  }
}

const languages = schemas['Job']!['properties']['language']['enum'] as string[];
const out = [
  '// Generated by scripts/generate.ts from the HRVoice OpenAPI document. Do not edit.',
  '',
  `export const OPENAPI_VERSION = ${JSON.stringify(doc['info']['version'])};`,
  `export const LANGUAGES = ${JSON.stringify(languages)} as const;`,
  '',
  ...Object.entries(schemas).map(([name, s]) => `export type ${nameOf(name)} = ${ts(s)};\n`),
  '/** Every /v1 operation: "<METHOD> <path>" -> query, body and 2xx response. */',
  'export interface Operations {',
  ...ops,
  '}',
  '',
].join('\n');
writeFileSync(join(here, '../src/generated.ts'), out);

// ---- Python (TypedDicts) ----

function py(s: Schema): string {
  if (s['$ref']) return nameOf(String(s['$ref']).split('/').pop()!);
  if (s['const'] !== undefined) return `Literal[${JSON.stringify(s['const']).replace(/^true$/, 'True')}]`;
  if (s['enum']) return `Literal[${(s['enum'] as unknown[]).map((v) => JSON.stringify(v)).join(', ')}]`;
  const alts = s['anyOf'] ?? s['oneOf'];
  if (alts) return (alts as Schema[]).map(py).join(' | ');
  const t = s['type'];
  if (Array.isArray(t)) return t.map((x) => py({ ...s, type: x })).join(' | ');
  switch (t) {
    case 'string':
      return 'str';
    case 'number':
      return 'float';
    case 'integer':
      return 'int';
    case 'boolean':
      return 'bool';
    case 'null':
      return 'None';
    case 'array':
      return `list[${py(s['items'] ?? {})}]`;
    case 'object':
      return 'dict[str, Any]'; // nested objects stay plain dicts
    default:
      return 'Any';
  }
}

const pyClasses = Object.entries(schemas).map(([name, s]) => {
  const req = new Set<string>(s['required'] ?? []);
  const fields = Object.entries((s['properties'] ?? {}) as Record<string, Schema>).map(([k, v]) =>
    `    ${k}: ${req.has(k) ? py(v) : `NotRequired[${py(v)}]`}`,
  );
  return `class ${nameOf(name)}(TypedDict):\n${fields.join('\n') || '    pass'}\n`;
});
writeFileSync(
  join(here, '../../sdk-python/src/hrvoice/_generated.py'),
  [
    '# Generated by packages/sdk-js/scripts/generate.ts from the HRVoice OpenAPI document. Do not edit.',
    'from __future__ import annotations',
    '',
    'from typing import Any, Literal, NotRequired, TypedDict',
    '',
    `LANGUAGES = (${languages.map((l) => JSON.stringify(l)).join(', ')})`,
    '',
    '',
    pyClasses.join('\n\n'),
  ].join('\n'),
);

console.log(`generated ${Object.keys(schemas).length} schemas, ${ops.length} operations`);
